#!/usr/bin/env python3
"""Train the tiny attack-ranking network on synthetic tactical examples."""

import argparse
from pathlib import Path

import numpy as np


INPUTS = 4
HIDDEN = 12


def make_data(count, rng):
    features = rng.random((count, INPUTS), dtype=np.float32)
    features[:, 1] = (features[:, 1] > 0.78).astype(np.float32)
    # Teach the model to favor damage and decisive hits while accounting for cost.
    targets = (2.0 * features[:, 0] + 3.0 * features[:, 1]
               - 0.15 * features[:, 3]).astype(np.float32)
    return features, targets[:, None]


def train(seed):
    rng = np.random.default_rng(seed)
    x, y = make_data(16000, rng)
    w1 = rng.normal(0, 0.25, (INPUTS, HIDDEN)).astype(np.float32)
    b1 = np.zeros((1, HIDDEN), dtype=np.float32)
    w2 = rng.normal(0, 0.25, (HIDDEN, 1)).astype(np.float32)
    b2 = np.zeros((1, 1), dtype=np.float32)
    params = [w1, b1, w2, b2]
    first = [np.zeros_like(p) for p in params]
    second = [np.zeros_like(p) for p in params]
    beta1, beta2, rate, epsilon = 0.9, 0.999, 0.01, 1e-8
    batch_size, steps = 256, 7000

    for step in range(1, steps + 1):
        indices = rng.integers(0, len(x), batch_size)
        xb, yb = x[indices], y[indices]
        hidden = np.maximum(xb @ w1 + b1, 0.0)
        prediction = hidden @ w2 + b2
        error = prediction - yb
        grad_prediction = (2.0 / batch_size) * error
        grad_w2 = hidden.T @ grad_prediction
        grad_b2 = grad_prediction.sum(axis=0, keepdims=True)
        grad_hidden = grad_prediction @ w2.T
        grad_hidden *= (xb @ w1 + b1) > 0.0
        gradients = [xb.T @ grad_hidden,
                     grad_hidden.sum(axis=0, keepdims=True),
                     grad_w2, grad_b2]

        for index, (parameter, gradient) in enumerate(zip(params, gradients)):
            first[index] = beta1 * first[index] + (1.0 - beta1) * gradient
            second[index] = beta2 * second[index] + (1.0 - beta2) * gradient**2
            corrected_first = first[index] / (1.0 - beta1**step)
            corrected_second = second[index] / (1.0 - beta2**step)
            parameter -= rate * corrected_first / (np.sqrt(corrected_second) + epsilon)

    test_x, test_y = make_data(4000, rng)
    prediction = np.maximum(test_x @ w1 + b1, 0.0) @ w2 + b2
    mae = float(np.mean(np.abs(prediction - test_y)))
    if mae > 0.08:
        raise RuntimeError(f"Model validation MAE is too high: {mae:.4f}")
    return params, mae


def write_header(path, params, mae):
    w1, b1, w2, b2 = params

    def array(name, values):
        rows = values if values.ndim == 2 else values.reshape(1, -1)
        body = ",\n".join(
            "    {" + ", ".join(f"{float(value):.8f}f" for value in row) + "}"
            for row in rows
        )
        return f"static const float {name}[{rows.shape[0]}][{rows.shape[1]}] = {{\n{body}\n}};\n"

    content = (
        "#ifndef BOT_MODEL_H\n#define BOT_MODEL_H\n\n"
        "/* Generated by tools/train_bot_model.py from synthetic tactical examples. */\n"
        f"/* Held-out mean absolute error: {mae:.5f}. */\n"
        f"#define BOT_NN_INPUTS {INPUTS}\n#define BOT_NN_HIDDEN {HIDDEN}\n\n"
        + array("BOT_NN_W1", w1)
        + "\n"
        + array("BOT_NN_B1", b1)
        + "\n"
        + array("BOT_NN_W2", w2.T)
        + "\n"
        + array("BOT_NN_B2", b2)
        + "\n#endif\n"
    )
    Path(path).write_text(content, encoding="ascii")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="tools/bot_model.h")
    parser.add_argument("--seed", type=int, default=20261021)
    args = parser.parse_args()
    params, mae = train(args.seed)
    write_header(args.output, params, mae)
    print(f"Wrote {args.output}; held-out MAE={mae:.5f}")


if __name__ == "__main__":
    main()
